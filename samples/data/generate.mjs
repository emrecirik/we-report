// Generates samples/data/seed.sql — the fictional sample dataset every sample backend loads.
// Deterministic (seeded PRNG): rerunning produces the same file. All names are invented.
// Usage: node samples/data/generate.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

let seed = 20261019;
const rand = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const pick = (list) => list[Math.floor(rand() * list.length)];

const firstNames = ['Ayla', 'Deniz', 'Kerem', 'Selin', 'Mert', 'Ece', 'Bora', 'Nil', 'Cem', 'Defne', 'Arda', 'Zeynep', 'Emir', 'Lara', 'Kaan', 'İpek'];
const lastNames = ['Yıldızkaya', 'Akdere', 'Tunçbilek', 'Erenköy', 'Karapınar', 'Gökdemir', 'Sarıçam', 'Uluova', 'Demirtaş', 'Kocaoğlu'];
const cities = ['Fallowick', 'Ashbourne', 'Merrowdale', 'Thistlebay', 'Corran', 'Highmere', 'Eastvale', 'Brindleford'];
const categories = ['Beverages', 'Bakery', 'Dairy', 'Pantry', 'Snacks'];
const productNames = {
  Beverages: ['Black tea 1 kg', 'Ground coffee 250 g', 'Apple juice 1 L', 'Mineral water 6x1.5 L'],
  Bakery: ['Sourdough loaf', 'Sesame ring', 'Butter croissant 4 pcs', 'Rye bread'],
  Dairy: ['Feta cheese 500 g', 'Yoghurt 1 kg', 'Butter 250 g', 'Kefir 1 L'],
  Pantry: ['Olive oil 1 L', 'Red lentils 1 kg', 'Bulgur 2.5 kg', 'Honey 850 g'],
  Snacks: ['Hazelnuts 500 g', 'Dried apricots 500 g', 'Chickpea crisps', 'Dark chocolate 80 g'],
};
const statuses = ['new', 'preparing', 'shipped', 'delivered', 'cancelled'];

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = [
  '-- we-report sample dataset (fictional). Generated by samples/data/generate.mjs — do not edit.',
  'CREATE TABLE customers (id INTEGER PRIMARY KEY, name VARCHAR(100) NOT NULL, city VARCHAR(60) NOT NULL, email VARCHAR(120) NOT NULL, credit_limit DECIMAL(12,2) NOT NULL);',
  'CREATE TABLE products (id INTEGER PRIMARY KEY, code VARCHAR(20) NOT NULL, name VARCHAR(100) NOT NULL, category VARCHAR(40) NOT NULL, price DECIMAL(12,2) NOT NULL);',
  'CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL, order_date DATE NOT NULL, status VARCHAR(20) NOT NULL);',
  'CREATE TABLE order_lines (id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL, product_id INTEGER NOT NULL, qty INTEGER NOT NULL, price DECIMAL(12,2) NOT NULL);',
];

for (let i = 1; i <= 40; i++) {
  const name = `${pick(firstNames)} ${pick(lastNames)}`;
  const email = `customer${i}@example.com`;
  lines.push(`INSERT INTO customers VALUES (${i}, ${q(name)}, ${q(pick(cities))}, ${q(email)}, ${Math.round(rand() * 50) * 1000});`);
}
let productId = 0;
for (const category of categories) {
  for (const name of productNames[category]) {
    productId++;
    // GS1 in-store prefix 29: can never collide with a real product's EAN.
    const code = `29${String(100000 + productId).padStart(6, '0')}`;
    lines.push(`INSERT INTO products VALUES (${productId}, ${q(code)}, ${q(name)}, ${q(category)}, ${(Math.round((5 + rand() * 245) * 100) / 100).toFixed(2)});`);
  }
}
let lineId = 0;
for (let o = 1; o <= 150; o++) {
  const day = new Date(Date.UTC(2026, 0, 1) + Math.floor(rand() * 290) * 86400000).toISOString().slice(0, 10);
  lines.push(`INSERT INTO orders VALUES (${o}, ${1 + Math.floor(rand() * 40)}, ${q(day)}, ${q(pick(statuses))});`);
  const count = 1 + Math.floor(rand() * 5);
  for (let l = 0; l < count; l++) {
    const p = 1 + Math.floor(rand() * productId);
    lines.push(`INSERT INTO order_lines VALUES (${++lineId}, ${o}, ${p}, ${1 + Math.floor(rand() * 12)}, ${(Math.round((5 + rand() * 245) * 100) / 100).toFixed(2)});`);
  }
}

const out = join(dirname(fileURLToPath(import.meta.url)), 'seed.sql');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out} (${lines.length} statements)`);
